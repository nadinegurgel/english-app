import { and, eq, isNull } from "drizzle-orm";
import { z } from "zod";
import { db } from "../db/client.js";
import { dictionaryEntries, dictionaryExampleSentences } from "../db/schema.js";
import { env } from "../env.js";
import { HttpError } from "../lib/http-errors.js";
import { normalizeTerm, sentenceContainsTerm } from "../lib/normalize.js";
import { askClaude, isAiEnabled } from "./claude.js";
import { ensureEntries, getEntries, getExampleSentences } from "./dictionary.js";

const SYSTEM_PROMPT = `You help a Brazilian university student learn English vocabulary.
For each English word or expression you receive, write:
- meaningPt: its most common meaning in Brazilian Portuguese, short (1 to 4 words). If there are two very common meanings, separate them with a comma.
- exampleSentence: one natural English sentence at CEFR level B1, 8 to 18 words, set in everyday life or university life.

Rules for exampleSentence:
- It must contain the word or expression exactly as given (same spelling and form), because it will be used as a fill-in-the-blank quiz.
- The context must make the meaning clear enough to guess the missing word.
- It must use a different situation from every sentence listed under "avoid".
- Use simple, modern, natural English. No names of real people or brands.
Return the items in the same order you received them.`;

const SuggestionsSchema = z.object({
  items: z.array(
    z.object({
      term: z.string(),
      meaningPt: z.string(),
      exampleSentence: z.string(),
    }),
  ),
});

export type SuggestionRequest = {
  term: string;
  // Sentences already shown to the user for this term, most recent last.
  seen: string[];
};

export type Suggestion = {
  term: string;
  meaningPt: string;
  exampleSentence: string;
  // False when the sentence does not contain the exact term and needs a manual fix.
  sentenceHasTerm: boolean;
  // True when nothing had to be generated by AI for this term.
  fromDictionary: boolean;
};

export function pickStored(
  stored: string[],
  seen: string[],
  limit = env.EXAMPLE_SENTENCES_PER_WORD,
): { sentence: string; needsAi: boolean } {
  const seenSet = new Set(seen.map((s) => s.trim()));
  // 1. A stored sentence the user has not seen yet.
  const unseen = stored.find((sentence) => !seenSet.has(sentence));
  if (unseen) return { sentence: unseen, needsAi: false };
  // 2. Room left in the dictionary: ask the AI for a new one.
  if (stored.length < limit) return { sentence: "", needsAi: true };
  // 3. Dictionary full: rotate, avoiding the sentence currently on screen.
  const current = seen.at(-1)?.trim();
  const others = stored.filter((sentence) => sentence !== current);
  const pool = others.length ? others : stored;
  return { sentence: pool[Math.floor(Math.random() * pool.length)] ?? "", needsAi: false };
}

/**
 * Meaning and example sentence for each term, from the shared dictionary when possible. The AI is
 * only asked when the user has seen every stored sentence and the term still has room for more,
 * or when the term has no meaning yet.
 */
export async function suggestExamples(requests: SuggestionRequest[]): Promise<Suggestion[]> {
  await ensureEntries(requests.map((request) => ({ term: request.term })));
  const keys = requests.map((request) => normalizeTerm(request.term));
  const [entries, examples] = await Promise.all([getEntries(keys), getExampleSentences(keys)]);

  const plans = requests.map((request, index) => {
    const key = keys[index]!;
    const stored = examples.get(key) ?? [];
    const pick = pickStored(stored, request.seen);
    const meaningPt = entries.get(key)?.meaningPt ?? "";
    return { ...request, key, stored, ...pick, meaningPt, needsAi: pick.needsAi || !meaningPt };
  });

  const toGenerate = plans.filter((plan) => plan.needsAi);
  if (toGenerate.length > 0) {
    if (!isAiEnabled) {
      if (plans.every((plan) => !plan.sentence && !plan.meaningPt)) {
        throw new HttpError(503, "AI suggestions are not configured. Set ANTHROPIC_API_KEY.");
      }
    } else {
      const output = await askClaude({
        system: SYSTEM_PROMPT,
        content: toGenerate
          .map((plan) => {
            const avoid = [...plan.stored, ...plan.seen].map((s) => `    - ${s}`).join("\n");
            return `- ${plan.term}${avoid ? `\n  avoid:\n${avoid}` : ""}`;
          })
          .join("\n"),
        schema: SuggestionsSchema,
      });
      // Match by term rather than position, in case the model reorders or skips items.
      const byTerm = new Map(output.items.map((item) => [normalizeTerm(item.term), item]));

      for (const plan of toGenerate) {
        const item = byTerm.get(plan.key);
        if (!item) continue;
        if (!plan.meaningPt && item.meaningPt.trim()) {
          plan.meaningPt = item.meaningPt.trim();
          await db
            .update(dictionaryEntries)
            .set({ meaningPt: plan.meaningPt })
            .where(
              and(eq(dictionaryEntries.normalizedTerm, plan.key), isNull(dictionaryEntries.meaningPt)),
            );
        }
        const sentence = item.exampleSentence.trim();
        if (!sentence) continue;
        if (!plan.sentence) plan.sentence = sentence;
        // The sentence is kept even when only the meaning was missing, since it is already paid for.
        // Only sentences that work as a quiz blank are worth sharing.
        if (
          sentenceContainsTerm(sentence, plan.term) &&
          !plan.stored.includes(sentence) &&
          plan.stored.length < env.EXAMPLE_SENTENCES_PER_WORD
        ) {
          await db.insert(dictionaryExampleSentences).values({ normalizedTerm: plan.key, sentence });
        }
      }
    }
  }

  return plans.map((plan) => ({
    term: plan.term,
    meaningPt: plan.meaningPt,
    exampleSentence: plan.sentence,
    sentenceHasTerm: plan.sentence !== "" && sentenceContainsTerm(plan.sentence, plan.term),
    fromDictionary: !plan.needsAi,
  }));
}

const RELATED_SYSTEM_PROMPT = `You help a Brazilian university student grow an English vocabulary set.
You receive the words already in the set. Infer the set's theme and level from them, then suggest new English words or expressions that:
- fit the same theme or situations,
- have the same difficulty as the given words (never above CEFR B2),
- are common and useful in real life, including phrasal verbs and expressions when they fit,
- are not any of the given or excluded words, nor just a different form of them (for example "deadlines" for "deadline").
For each suggestion return the term in its base form and meaningPt: its most common meaning in Brazilian Portuguese, short (1 to 4 words).`;

const RelatedSchema = z.object({
  suggestions: z.array(z.object({ term: z.string(), meaningPt: z.string() })),
});

export type RelatedWord = { term: string; meaningPt: string };

/** Suggests `count` new words for a set, never returning a term from `exclude`. */
export async function suggestRelatedWords(
  setTerms: string[],
  exclude: string[],
  count: number,
): Promise<RelatedWord[]> {
  const output = await askClaude({
    system: RELATED_SYSTEM_PROMPT,
    content: [
      `Words in the set:\n${setTerms.map((term) => `- ${term}`).join("\n")}`,
      exclude.length ? `Do not suggest:\n${exclude.map((term) => `- ${term}`).join("\n")}` : "",
      // Ask for a few extra in case some are filtered out as duplicates.
      `Suggest ${count + 3} words.`,
    ]
      .filter(Boolean)
      .join("\n\n"),
    schema: RelatedSchema,
  });

  const excluded = new Set([...setTerms, ...exclude].map(normalizeTerm));
  const result: RelatedWord[] = [];
  for (const suggestion of output.suggestions) {
    const term = suggestion.term.trim().replace(/\s+/g, " ");
    const key = normalizeTerm(term);
    if (!term || excluded.has(key)) continue;
    excluded.add(key);
    result.push({ term, meaningPt: suggestion.meaningPt.trim() });
    if (result.length === count) break;
  }
  // The meaning comes for free here, so the dictionary keeps it for later.
  await ensureEntries(result.map((word) => ({ term: word.term, aiMeaningPt: word.meaningPt })));
  return result;
}
